  var STORAGE_KEY = "coop-lang";
  var currentLang = "zh";
  var langSaved = false;

  try {
    var saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "zh" || saved === "en") { currentLang = saved; langSaved = true; }
  } catch (e) { /* file:// 环境下 localStorage 可能不可用，忽略 */ }

  /* ── 自动识别语言 ─────────────────────────────────────────────
     1) URL 参数 ?lang=zh / ?lang=en 优先（方便发链接、放二维码）
     2) 用户手动点过语言按钮 → 用他选的（存在 localStorage）
     3) 都没有 → 看浏览器首选语言：中文系统给中文，其余一律英文
     ──────────────────────────────────────────────────────────── */
  var urlLang = "";
  try {
    var m = String(location.search || "").match(/[?&]lang=(zh|en)(?:&|$)/i);
    if (m) urlLang = m[1].toLowerCase();
  } catch (e) { /* 忽略 */ }

  if (urlLang === "zh" || urlLang === "en") {
    currentLang = urlLang;
    try { localStorage.setItem(STORAGE_KEY, currentLang); } catch (e) { /* 忽略 */ }
  } else if (!langSaved) {
    var firstLang = "";
    try {
      firstLang = String((navigator.languages && navigator.languages[0]) || navigator.language || "").toLowerCase();
    } catch (e) { /* 忽略 */ }
    currentLang = firstLang.indexOf("zh") === 0 ? "zh" : "en";
  }

  function t(key) {
    var table = I18N[currentLang] || I18N.zh;
    if (table[key] !== undefined) return table[key];
    if (I18N.zh[key] !== undefined) return I18N.zh[key];
    return key;
  }

  function applyI18n() {
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    /* 支持 placeholder 翻译（搜索框等输入提示） */
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    var titleKey = document.documentElement.getAttribute("data-title");
    if (titleKey) document.title = t(titleKey);
    document.documentElement.lang = currentLang === "zh" ? "zh-CN" : "en";
    document.querySelectorAll(".lang-btn .lang-label").forEach(function (el) {
      el.textContent = currentLang === "zh" ? "EN" : "中文";
    });
  }

  function switchLang() {
    currentLang = currentLang === "zh" ? "en" : "zh";
    try { localStorage.setItem(STORAGE_KEY, currentLang); } catch (e) { /* 忽略 */ }
    applyI18n();
    if (window.renderPage) window.renderPage();
    try { window.dispatchEvent(new Event("circu-lang-changed")); } catch (e) { /* 忽略 */ }
  }

  window.t = t;
  window.getLang = function () { return currentLang; };
  window.applyI18n = applyI18n;

  document.addEventListener("DOMContentLoaded", function () {
    applyI18n();
    if (window.renderPage) window.renderPage();
  });

  /* 事件委托：语言按钮无论何时创建、是否被遮挡，点击都可靠触发 */
  document.addEventListener("click", function (e) {
    var btn = e.target && e.target.closest ? e.target.closest(".lang-btn") : null;
    if (btn) {
      e.preventDefault();
      switchLang();
    }
  });
